def _cell(value: object) -> str:
    return "" if value is None else str(value).replace("|", "/")


def registry_table(status: str) -> str:
    lines = ["| model | modality | width | loader | licence |", "|---|---|---|---|---|"]
    for m in supported_models(status):
        lines.append(f"| `{m.model_id}` | {m.modality} | {'?' if m.dimension is None else m.dimension} | "
                     f"`{m.loader}` | {_cell(m.license) or 'not declared'} |")
    return "\n".join(lines)


def notes_list(status: str) -> str:
    lines = [f"- `{m.model_id}`: {m.notes}" for m in supported_models(status) if m.notes]
    return "\n".join(lines)


def measured_table() -> str:
    header = ("| model | dataset | float baseline | largest compression whose interval stayed at or above 0.97 "
              "on every dataset | x float32 | retention [interval] |")
    lines = [header, "|---|---|---|---|---|---|"]
    for model_id in measured_models():
        entries = measured_results(model_id)
        shortlist = measured_shortlist(model_id, 0.97)
        best = shortlist[0] if shortlist else None
        for dataset, entry in entries.items():
            name = dataset.split("/")[-1]
            base = f"{entry['metric']} {entry['baseline']:.3f}"
            if best is None:
                lines.append(f"| `{model_id}` | {name} | {base} | none | | |")
                continue
            d = best["datasets"][dataset]
            lo, hi = d["retention_interval"]
            lines.append(f"| `{model_id}` | {name} | {base} | `{best['label']}` | {d['compression']:.1f} | "
                         f"{d['retention']:.3f} [{lo:.3f}, {hi:.3f}] |")
    return "\n".join(lines)


def render() -> str:
    counts = {s: len(supported_models(s)) for s in ("measured", "untested", "unverified")}
    loaders = "\n".join(f"`{name}`" + ("," if i < len(supported_loaders()) - 1 else ".")
                        for i, name in enumerate(supported_loaders()))
    parts = [HEAD.replace("LOADERS", loaders)]
    parts.append(f"The registry holds {len(MODELS)} models: {counts['measured']} measured, "
                 f"{counts['untested']} untested, {counts['unverified']} unverified. The facts of the entries "
                 "that were not measured here (width, loading calls, licence) were read from each model's card "
                 "and repository files on 2026-10-12, at the revision the entry records.\n")
    for status, title in (("measured", "Measured"), ("untested", "Untested"), ("unverified", "Unverified")):
        parts.append(f"### {title} ({counts[status]})\n\n{registry_table(status)}\n")
        notes = notes_list(status)
        if notes:
            parts.append(f"Loading notes:\n\n{notes}\n")
    parts.append(MEASURED_HEAD + measured_table() + "\n")
    without_rows = [m.model_id for m in supported_models("measured") if m.model_id not in measured_models()]
    parts.append("Measured models without rows in the catalogue: "
                 + ", ".join(f"`{m}`" for m in without_rows)
                 + ". `vidore/colSmol-256M` was measured on generated corpora only, which have no fixed-pipeline "
                   "study of this form; `vidore/colqwen2-v1.0` gives the same vectors as its pre-merged copy, "
                   "which holds the rows.\n")
    parts.append("The runs added in 0.4.0 (Kaggle, two T4 GPUs each, the same two 500-page splits and study "
                 "scripts as the earlier wide-model run):\n\n"
                 "| model | revision | inference | record |\n|---|---|---|---|\n"
                 "| `nvidia/nemotron-colembed-vl-8b-v2` | `34b64061` | float16 (no float32 encoding exists; "
                 "retention is against the float16-inference baseline) | `reports/universal/wide/NEMOTRON_8B.md` |\n"
                 "| `athrael-soju/colqwen3.5-4.5B-v3` | `c4ea4b92` | float32 | "
                 "`reports/universal/wide/logs/colqwen3.5-4.5B-v3/` |\n"
                 "| `TomoroAI/tomoro-colqwen3-embed-4b` | `13517a29` | float32 | "
                 "`reports/universal/wide/logs/tomoro-colqwen3-embed-4b/` |\n\n"
                 "The last two were encoded by the script stored beside their logs (`enc_generic.py`). The "
                 "in-package loaders repeat that script's calls and have not themselves been run on those "
                 "checkpoints. The 8B was a candidate of the held-out pool of the research protocol; having "
                 "been compressed here, it is no longer eligible for that protocol.\n")
    parts.append("## 5. Known models without a loader here\n\n"
                 "These are late-interaction retrievers (checked on their model cards, 2026-10-12) that no "
                 "loader of this package builds. Encode with the model's own code and pass the arrays "
                 "(`ArrayAdapter`).\n\n| model | width | why |\n|---|---|---|\n"
                 + "\n".join(f"| `{m}` | {w} | {why} |" for m, w, why in NO_LOADER)
                 + "\n\nNot late-interaction retrievers, and so not registered:\n\n"
                 + "\n".join(f"- `{m}`: {why}" for m, why in NOT_MULTI_VECTOR) + "\n")
    parts.append(TAIL.lstrip("\n"))
    return "\n".join(parts)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="compare with the committed file instead of writing")
    a = ap.parse_args()
    text = render()
    if a.check:
        current = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date; run scripts/build_models_doc.py")
            return 1
        print("the models page is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(text.splitlines())} lines")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
