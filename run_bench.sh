#!/usr/bin/env bash
# Run the full ablation with the real ColSmol-256M encoder.
#
# Expect ~30-50 s/page of encoding on a CPU-only machine, so a 60-page corpus
# takes roughly an hour on the first run. The encode pass is cached to
# data/cache/, so re-running to add or change an ablation row takes seconds.
#
# Two gotchas worth knowing before you conclude this script has hung:
#
#   * On a venv built from the Microsoft Store Python, `.venv/Scripts/python.exe`
#     is a ~10 MB re-exec stub and the real interpreter runs as `python3.13.exe`.
#     `Get-Process python` matches only the stub, which sits at ~0 % CPU for the
#     whole run and looks exactly like a hang. Check `Get-Process python3.13`.
#   * Do not edit this file while it is running. Bash reads a script by byte
#     offset as it executes, so an edit shifts the offsets and the shell resumes
#     mid-word — producing a baffling "command not found" on a line that is fine.
#
# Hub metadata calls are bounded so a flaky network cannot wedge the run. Full
# offline mode does not work here: the processor's tokenizer config resolves to
# a repo that the checkpoint download does not fully populate.
set -euo pipefail

export HF_HUB_ETAG_TIMEOUT=10
export HF_HUB_DOWNLOAD_TIMEOUT=30
export TOKENIZERS_PARALLELISM=false
export PYTHONUNBUFFERED=1

OUT="${1:-reports/colsmol}"
CACHE="${2:-data/cache/colsmol.npz}"
mkdir -p "$OUT" "$(dirname "$CACHE")"

./.venv/Scripts/python.exe -m optivision.cli bench \
  data/corpus/pdfs data/corpus/queries.json \
  -c configs/colsmol.yaml --out "$OUT" --sweep --cache "$CACHE" 2>&1 | tee "$OUT/run.log"
